def repo(*parts):
    """Return a path relative to cases/ai-portfolio/src that reaches a sibling case."""
    # src -> ai-portfolio -> cases -> sibling case
    return "../../" + "/".join(parts)


def hero(prefix, dark_variant=None, light_variant=None):
    """Return hero screenshot paths for a case prefix.

    Most prefixes use <prefix>_portfolio_dark.png / _portfolio_light.png.
    A few (PR, RG) use <prefix>-portfolio-dark.png.
    """
    if dark_variant is None:
        dark_variant = f"{prefix}_portfolio_dark.png"
        light_variant = f"{prefix}_portfolio_light.png"
    return {
        "dark": f"assets/screenshots/{dark_variant}",
        "light": f"assets/screenshots/{light_variant}",
    }


def cta(text, href="#", primary=False, target_blank=True, disabled=False):
    return {
        "text": text,
        "href": href,
        "primary": primary,
        "target_blank": target_blank,
        "disabled": disabled,
    }


